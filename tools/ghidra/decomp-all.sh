#!/usr/bin/env bash
# Decompile all of nwmain-linux into a read-only listing (DecompAll.java). Hours, not minutes.
#
#   tools/ghidra/decomp-all.sh $NWN_DECOMP/8193.37-17 [threads]
#
# The output is Beamdog's code: it lives outside the repo and is never committed or published.
# One dump per client build; regenerate on update day (docs/update-day.md).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"

out="${1:?output dir, e.g. $NWN_DECOMP/<build>}"
threads="${2:-8}"
[[ -e "$out" ]] && { echo "refusing: $out exists (a dump is read-only; delete it to regenerate)" >&2; exit 1; }
mkdir -p "$out"
out="$(cd "$out" && pwd)"

"$HERE/headless.sh" nwmain-linux DecompAll.java "$out" "$threads" > "$out/headless.log" 2>&1
grep -q 'DecompAll: done' "$out/headless.log" || { echo "FAILED, see $out/headless.log" >&2; exit 1; }

cat > "$out/README.md" <<'EOF'
# nwmain-linux, decompiled (read-only)

Ghidra output of every function, generated by `tools/ghidra/DecompAll.java` in NWNCX:EE.
Decompiler output, not source: types and field names are only as good as the Ghidra project's.
Provenance (program hash, Ghidra version, counts) is in `MANIFEST`.

- `symbols.tsv`: addr, size, name, signature, mangled, file, line, status. **Start here.**
  `rg -F 'Scene::RenderBeams' symbols.tsv` gives file + line; then read ~80 lines from there.
- `src/<Namespace>.c`: one file per class; `std::vector<..>` becomes `std.vector_.._.c`; free functions are in `_global.c`.
  Each function starts with `// ===== Ns::name @addr`.
- `callgraph.tsv`: caller_addr, caller, callee_addr, callee (direct calls; thunks resolved to targets).
  Callers of X: `awk -F'\t' '$4 == "X"' callgraph.tsv`. Callees: `awk -F'\t' '$2 == "X"' callgraph.tsv`.
  Virtual calls and function-pointer calls (GL entry points) are NOT edges; grep `src/` for those.
- `types.h`: the project's data types as C.
- status `timeout`/`fail`: redo one with `tools/ghidra/DecompOne.java`.
EOF
chmod -R a-w "$out"
grep -E 'DecompAll: done' "$out/headless.log"
